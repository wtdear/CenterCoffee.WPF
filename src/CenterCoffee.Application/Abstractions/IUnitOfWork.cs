using CenterCoffee.Domain.Repositories;

namespace CenterCoffee.Application.Abstractions
{
    /// <summary>
    /// Единица работы: даёт доступ к репозиториям и сохраняет изменения атомарно.
    /// Пока реализован только складской контур, остальные репозитории появятся
    /// по мере вывода модулей из стадии разработки.
    /// </summary>
    public interface IUnitOfWork
    {
        /// <summary>
        /// Признак того, что данные можно использовать. Становится false, если хранилище
        /// не удалось прочитать или перечитать (например, после восстановления из копии).
        /// Пока значение false, чтение и сохранение запрещены: иначе следующая запись
        /// могла бы затереть актуальный файл устаревшими данными из памяти.
        /// </summary>
        bool IsReady { get; }

        IIngredientRepository Ingredients { get; }

        IStockMovementRepository Movements { get; }

        /// <summary>Сохраняет изменения; выбрасывает, если данные не готовы к записи.</summary>
        void SaveChanges();

        /// <summary>
        /// Перечитывает данные из хранилища и заново создаёт репозитории.
        /// Вызывается после восстановления из резервной копии: без этого в памяти
        /// остались бы старые данные и следующее сохранение затёрло бы восстановленные.
        /// Несохранённые изменения при перечитывании отбрасываются. При ошибке чтения
        /// единица работы остаётся непригодной до успешного повтора.
        /// </summary>
        void Reload();
    }
}
